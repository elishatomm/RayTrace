def render_readme(report: Report) -> str:
    design = report["design"]
    model = _get(report, "runtime", "model")
    attacks = "\n".join(f"  - `{attack}` ({', '.join(families_of(design, attack))}; {channel}): {ATTACK_ASKS[attack]}."
                        for attack, channel in _get(design, "channels").items())  # type: ignore[union-attr]
    intro = INTRO.format(
        seed_offset=_get(design, "seed_offset"), split=_get(design, "split"),
        lead_minutes=int(_get(design, "order_note_lead_ms")) // 60_000, attacks=attacks,  # type: ignore[call-overload]
        model_line=f"`{_get(model, 'model')}` (digest `{str(_get(model, 'model_digest'))[:12]}`), thinking off, prompt "
                   f"`{_get(model, 'prompt_version')}`, validator `{_get(report, 'versions', 'validator')}`",
    )
    sections: Sequence[str] = [intro, *headline(report), *results_table(report), *gates(report), *per_run_table(report),
                               *build_section(report), *runtime_section(report), LIMITATIONS, REPRODUCE]
    return "\n".join(sections).rstrip("\n") + "\n"


def families_of(design: JsonValue, attack: str) -> list[str]:
    return [family for family, attacks in _get(design, "targets").items() if attack in attacks]  # type: ignore[union-attr, operator]
